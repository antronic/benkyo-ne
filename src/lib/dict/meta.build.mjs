// Writes src/lib/dict/meta.data.ts: facts about the 26k common JMdict words that the
// lightweight rows in @johnmorrisdotca/jisho don't carry (part of speech, reading order).
// Run after upgrading the package:  node src/lib/dict/meta.build.mjs
// (src/lib/dict/meta.test.ts fails when the release no longer matches.)
import { writeFileSync } from 'node:fs';
import { loadCommonWords } from '@johnmorrisdotca/jisho/words';
import { loadEntry } from '@johnmorrisdotca/jisho/entries';

const GRAMMAR = new Set(['prt', 'aux', 'aux-v', 'aux-adj', 'cop', 'cop-da', 'conj', 'pref', 'suf', 'ctr']);
/** Reading marks that make a reading unsuitable as a pack word: irregular, out-dated, rarely-used, search-only. */
const BAD_READING = new Set(['ik', 'ok', 'rk', 'sk', 'oik']);
/** @param {string} s */
const fold = (s) => s.replace(/[ァ-ヶ]/g, (/** @type {string} */ c) => String.fromCharCode(c.charCodeAt(0) - 0x60));

const common = await loadCommonWords();
const readingsById = new Map();
for (const rows of common.entries.values())
	for (const r of rows) {
		if (r.id === undefined) continue;
		if (!readingsById.has(r.id)) readingsById.set(r.id, new Set());
		readingsById.get(r.id).add(r.reading);
	}

const phrase = [];
const grammar = [];
const secondary = [];
for (const id of [...readingsById.keys()].sort((a, b) => a - b)) {
	const e = await loadEntry(id);
	if (!e) continue;
	const pos0 = e.senses[0]?.pos ?? [];
	if (pos0.includes('exp')) phrase.push(id);
	else if (pos0.length && pos0.every((p) => GRAMMAR.has(p))) grammar.push(id);
	const first = e.readings[0] ? fold(e.readings[0].text) : '';
	const bad = [];
	for (const reading of readingsById.get(id)) {
		const er = e.readings.find((x) => fold(x.text) === fold(reading));
		const ok = fold(reading) === first && !(er?.marks ?? []).some((m) => BAD_READING.has(m));
		if (!ok) bad.push(reading);
	}
	if (bad.length) secondary.push(`${id.toString(36)}:${bad.sort().join(',')}`);
}

/** @param {number[]} ids */
const b36 = (ids) => ids.map((n) => n.toString(36)).join(' ');
const out = `// Generated by src/lib/dict/meta.build.mjs from JMdict (EDRDG, CC BY-SA 4.0) via @johnmorrisdotca/jisho. Do not edit.
// Covers the common words only. Ids are base 36.
export const META_RELEASE = ${JSON.stringify(common.release)};
/** Entries whose first sense is an expression (JMdict pos "exp"): いただきます, おねがいします… */
export const PHRASE_IDS = ${JSON.stringify(b36(phrase))};
/** Entries whose first sense is only particle/auxiliary/copula/conjunction/prefix/suffix/counter. */
export const GRAMMAR_IDS = ${JSON.stringify(b36(grammar))};
/** id:readings of common rows that are not the entry's first reading, or are marked irregular/out-dated/rare. */
export const SECONDARY_READINGS = ${JSON.stringify(secondary.join(' '))};
`;
writeFileSync(new URL('./meta.data.ts', import.meta.url), out);
console.log(`phrases ${phrase.length}, grammar ${grammar.length}, secondary ${secondary.length}, ${out.length} bytes`);
